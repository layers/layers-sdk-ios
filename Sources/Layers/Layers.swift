    // MARK: - Flush & Reset

    /// Default batch size for drain operations.
    private static let defaultBatchSize: UInt32 = 1000

    /// Flush queued events to the server (async version — preferred).
    /// Drains events from the Rust core queue, sends them over HTTP via URLSession,
    /// retries on transient failures, and requeues events if all retries are exhausted.
    public func flush() async -> SafeResult<Void> {
        guard let core = lockedCoreIfInitialized() else {
            let err = LayersError.notInitialized
            reportError(method: "flush", error: err)
            return .failure(err)
        }
        if enableDebug {
            os_log("flush()", log: Self.log, type: .debug)
        }
        return await withCheckedContinuation { continuation in
            _flushQueue.async { [weak self] in
                guard let self = self else {
                    continuation.resume(returning: .success(()))
                    return
                }
                let result = self.deliverBatch(core: core)
                continuation.resume(returning: result)
            }
        }
    }

    /// Flush queued events to the server (synchronous version).
    /// Blocks the calling thread until events are sent.
    ///
    /// - Warning: Do not call from the main thread in production. Prefer `flush()` instead.
    @discardableResult
    public func flushBlocking() -> SafeResult<Void> {
        guard let core = lockedCoreIfInitialized() else {
            let err = LayersError.notInitialized
            reportError(method: "flushBlocking", error: err)
            return .failure(err)
        }
        let semaphore = DispatchSemaphore(value: 0)
        let box = ResultBox<SafeResult<Void>>(.success(()))
        _flushQueue.async { [weak self] in
            guard let self = self else {
                semaphore.signal()
                return
            }
            box.value = self.deliverBatch(core: core)
            semaphore.signal()
        }
        // Cap at 45s (3 retries × 10s timeout + backoff)
        let result = semaphore.wait(timeout: .now() + 45)
        if result == .timedOut {
            os_log("flushBlocking timed out after 45s", log: Self.log, type: .error)
            return .failure(LayersError.networkError("flushBlocking timed out"))
        }
        return box.value
    }

    /// Core drain-and-deliver loop. Must be called on `_flushQueue` (serial).
    /// The serial queue guarantees mutual exclusion — no additional lock needed.
    ///
    /// Delivery policy lives in the Rust core (adr/0001-rust-owned-delivery-policy.md):
    /// one pre-flight gate (consent/DNT + Retry-After + circuit breaker via
    /// `shouldAttemptFlush`), one HTTP attempt, one post-flight report
    /// (`recordFlushResult`) whose verdict decides requeue vs drop. No
    /// wrapper-side retry loops or backoff — the next flush tick retries,
    /// gated by the core.
    private func deliverBatch(core: LayersCoreHandle) -> SafeResult<Void> {
        // Gate only when there's something to send: shouldAttemptFlush()
        // may claim the circuit breaker's half-open probe slot, which an
        // idle tick must not consume.
        if core.queueDepth() == 0 {
            return .success(())
        }
        if !core.shouldAttemptFlush() {
            if enableDebug {
                os_log("Flush skipped — core delivery gate closed", log: Self.log, type: .debug)
            }
            return .success(()) // Events stay in queue for later
        }

        // After a passed gate, EVERY pre-wire abort path must call
        // abortFlushAttempt() — it releases a claimed half-open breaker
        // probe WITHOUT counting a delivery failure (no request was made,
        // so neither success nor failure is true).

        // Drain a batch from the Rust queue
        let batchJson: String
        do {
            guard let json = try core.drainBatch(count: Self.defaultBatchSize) else {
                core.abortFlushAttempt()
                return .success(()) // Queue raced empty
            }
            batchJson = json
        } catch {
            core.abortFlushAttempt()
            let mapped = Self.mapError(error)
            reportError(method: "flush", error: mapped)
            return .failure(mapped)
        }

        // Get URL and headers from the Rust core
        let urlString: String
        let headersJson: String
        do {
            urlString = try core.eventsUrl()
            headersJson = try core.flushHeadersJson()
        } catch {
            // Cannot deliver without URL/headers — requeue events
            core.abortFlushAttempt()
            requeueSilently(core: core, batchJson: batchJson)
            let mapped = Self.mapError(error)
            reportError(method: "flush", error: mapped)
            return .failure(mapped)
        }

        guard let url = URL(string: urlString) else {
            core.abortFlushAttempt()
            requeueSilently(core: core, batchJson: batchJson)
            let err = LayersError.networkError("Invalid events URL: \(urlString)")
            reportError(method: "flush", error: err)
            return .failure(err)
        }

        // Build URLRequest with headers from Rust core
        var request = URLRequest(url: url)
        request.httpMethod = "POST"
        request.timeoutInterval = 10
        request.httpBody = batchJson.data(using: .utf8)
        guard Self.applyHeaders(from: headersJson, to: &request) else {
            core.abortFlushAttempt()
            requeueSilently(core: core, batchJson: batchJson)
            let err = LayersError.networkError("Failed to parse flush headers")
            reportError(method: "flush", error: err)
            return .failure(err)
        }

        // One attempt; the verdict for anything other than 2xx comes from
        // the core. A missing response (network error / timeout) is
        // reported as status 0.
        let semaphore = DispatchSemaphore(value: 0)
        var httpResponse: HTTPURLResponse?
        var networkError: Error?

        let task = URLSession.shared.dataTask(with: request) { _, response, error in
            networkError = error
            httpResponse = response as? HTTPURLResponse
            semaphore.signal()
        }
        task.resume()
        semaphore.wait()

        let status = httpResponse?.statusCode ?? 0
        let retryAfterHeader = httpResponse?.value(forHTTPHeaderField: "Retry-After")
        if let error = networkError {
            os_log("Flush failed (network): %{public}@", log: Self.log, type: .error, error.localizedDescription)
        }

        let verdict = core.recordFlushResult(
            status: UInt16(clamping: status),
            retryAfterHeader: retryAfterHeader
        )
        switch verdict {
        case .delivered:
            recordFlushResult(success: true, message: "HTTP \(status)")
            if enableDebug {
                os_log("Flush succeeded (HTTP %d)", log: Self.log, type: .debug, status)
            }
            return .success(())
        case .retryLater:
            // Transient — put the batch back; the next flush tick retries,
            // gated by the core's Retry-After guard and circuit breaker.
            // This is normal deferral, NOT a failure: no error callback
            // (parity with Kotlin/Flutter — spurious flush errors on every
            // flaky-network tick train apps to ignore the error listener).
            requeueSilently(core: core, batchJson: batchJson)
            let message = status == 0
                ? (networkError?.localizedDescription ?? "network error")
                : "HTTP \(status)"
            recordFlushResult(success: false, message: message)
            if enableDebug {
                os_log("Flush deferred (%{public}@), batch requeued", log: Self.log, type: .debug, message)
            }
            return .success(())
        case .drop:
            // Permanent rejection — identical bytes cannot succeed later;
            // retrying would wedge the queue behind a poison batch.
            os_log("Flush failed: HTTP %d (non-retryable, events dropped)", log: Self.log, type: .error, status)
            recordFlushResult(success: false, message: "HTTP \(status)")
            let err = LayersError.networkError("HTTP \(status)")
            reportError(method: "flush", error: err)
            return .failure(err)
        }
    }

    /// Requeue a drained batch back into the Rust core queue. Errors are swallowed.
    private func requeueSilently(core: LayersCoreHandle, batchJson: String) {
        do {
            _ = try core.requeueEvents(eventsJson: batchJson)
        } catch {
            os_log("Requeue failed: %{public}@", log: Self.log, type: .error, error.localizedDescription)
        }
    }

    /// Reset the SDK state, clearing user identity and properties.
    ///
    /// Note: This performs two separate calls to the core (clear identity, clear user properties).
    /// If the first succeeds but the second fails, the SDK may be in a partially-reset state.
    /// The returned result reflects the first failure encountered.
    /// Clear the SDK identity:
    /// - drops the `appUserId` set via `identify()`
    /// - rotates `device_id` and `anonymous_id` (server-side identity stitching uses both)
    /// - clears all super-properties registered via `setSuperProperties{Once}`
    /// - clears all multi-group memberships set via `setGroup` / `addGroup`
    /// - drops in-flight queued events (they belonged to the prior identity)
    /// - resets screen breadcrumbs and timed-event timers
    @discardableResult
    public func reset() -> SafeResult<Void> {
        guard let core = lockedCoreIfInitialized() else {
            let err = LayersError.notInitialized
            reportError(method: "reset", error: err)
            return .failure(err)
        }
        if enableDebug {
            os_log("reset()", log: Self.log, type: .debug)
        }
        do {
            try core.reset()
            lock.lock()
            _appUserId = nil
            lock.unlock()
            return .success(())
        } catch {
            let mapped = Self.mapError(error)
            reportError(method: "reset", error: mapped)
            return .failure(mapped)
        }
    }

    @discardableResult
    public func shutdown() -> SafeResult<Void> {
        guard let core = lockedCoreIfInitialized() else {
            let err = LayersError.notInitialized
            reportError(method: "shutdown", error: err)
            return .failure(err)
        }
        if enableDebug {
            os_log("shutdown()", log: Self.log, type: .debug)
        }
        do {
            try core.shutdown()

            // Cancel periodic timers
            lock.lock()
            _configTimer?.cancel()
            _configTimer = nil
            _flushTimer?.cancel()
            _flushTimer = nil
            lock.unlock()

            // Stop network monitor
            stopNetworkMonitor()

            #if os(iOS) || os(tvOS)
            lock.lock()
            if let observer = _backgroundObserver {
                NotificationCenter.default.removeObserver(observer)
                _backgroundObserver = nil
            }
            lock.unlock()
            #endif

            // Tear down Tier 2 auto-capture modules.
            lifecycle.detach()
            screenTracking.detach()
            #if canImport(StoreKit)
            if #available(iOS 15.0, macOS 13.0, tvOS 15.0, watchOS 8.0, *) {
                commerce.stopAutomaticPurchaseTracking()
            }
            #endif
            commerce.detach()

            // (Delivery-policy state — Retry-After gate, circuit breaker —
            // lives in the Rust core and dies with the handle below.)

            lock.lock()
            _core = nil
            _isInitialized = false
            _appUserId = nil
            _hadPriorSdkState = false
            _attributionDeeplinkId = nil
            _attributionGclid = nil
            _attributionFbclid = nil
            _attributionFbc = nil
            _attributionTtclid = nil
            _attributionMsclkid = nil
            _initListener = nil
            _configAppId = nil
            _configEnvironment = .production
            _configBaseUrl = nil
            _recentEvents = []
            _lastFlushResult = nil
            _featureFlagListeners.removeAll()
            _featureFlagListenersFired.removeAll()
            // Kill any in-flight deferred init chain from this instance.
            _initGeneration &+= 1
            lock.unlock()

            #if canImport(UIKit) && !os(watchOS)
            DispatchQueue.main.async { [weak self] in
                self?.hideDebugOverlay()
            }
            #endif
            return .success(())
        } catch {
            let mapped = Self.mapError(error)
            reportError(method: "shutdown", error: mapped)
            return .failure(mapped)
        }
    }

