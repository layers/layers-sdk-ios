// MARK: - SafeResult

/// Result type that guarantees the SDK never throws or crashes the host app.
public enum SafeResult<T: Sendable>: Sendable {
    case success(T)
    case failure(LayersError)
}

// MARK: - ResultBox

/// Thread-safe box for passing a value between a `Task` closure and a blocking caller.
/// Replaces `UnsafeMutablePointer` usage with a Sendable-safe reference type.
// Thread safety is guaranteed by the DispatchSemaphore in flushBlocking() — the Task writes
// before signal(), and the caller reads after wait().
private final class ResultBox<T: Sendable>: @unchecked Sendable {
    var value: T
    init(_ value: T) { self.value = value }
}

// MARK: - SendableJSONProps

/// Wraps a `[String: Any]` event-properties snapshot so it can cross a `@Sendable`
/// closure boundary (e.g. the attribution-resolve dispatch in `trackFirstLaunchEvents`).
/// `Any` is never provably `Sendable` to the compiler, but every value placed in these
/// dictionaries throughout the SDK is a JSON-serializable primitive (String, NSNumber,
/// Bool — see `LayersEvent.swift`'s `ParameterizedEvent`) built from local literals
/// immediately before the dictionary is handed off, and never mutated concurrently
/// afterward. `@unchecked` documents that invariant; it does not paper over one.
private struct SendableJSONProps: @unchecked Sendable {
    let value: [String: Any]
}

// MARK: - LayersCoreHandle Sendable

// `LayersCoreHandle` is UniFFI-generated (`Generated/LayersCore.swift`, do not edit) and
// ships with no Sendable conformance, so every capture of a `core: LayersCoreHandle`
// value in one of this file's `@Sendable` closures (flush's background queue hop, the
// URLSession config-fetch completion handler, the periodic-flush timer, etc.) is flagged
// under strict concurrency checking.
//
// The handle is genuinely safe to share across threads, not just "probably fine":
// - The Rust struct it wraps (`core/src/uniffi_api.rs`) derives `#[derive(uniffi::Object)]`,
//   which requires the exported type to be `Send + Sync` in Rust — UniFFI's generated
//   bindings call `&self` methods on it from whatever thread the platform wrapper is on.
// - Every mutable field of the wrapped `LayersCore` (`core/src/client.rs`) is behind a
//   `parking_lot::RwLock` or `Mutex`; there is no unsynchronized mutable state on the
//   Rust side for concurrent Swift calls to race on.
// - The Swift class itself (`Generated/LayersCore.swift`) adds no mutable state of its
//   own — it holds a single immutable `let pointer: UnsafeMutableRawPointer!` and every
//   method forwards straight into the Rust FFI call above.
//
// So the boundary that needs crossing is real (background delivery is the whole point
// of `deliverBatch`/`requeueSilently`), and restructuring every call site to avoid it
// would mean giving up the async flush design. `@unchecked` is correct here because the
// thread-safety argument lives in Rust, which the Swift compiler cannot see — this is
// not a blanket suppression, it is documenting an already-true invariant.
extension LayersCoreHandle: @unchecked Sendable {}

// MARK: - LayersError

/// All possible SDK errors. Mapped from Rust UniFfiError at the FFI boundary.
public enum LayersError: Error, LocalizedError, Sendable, Equatable {
    case notInitialized
    case invalidConfig(String)
    case networkError(String)
    case persistenceError(String)
    case queueFull
    case circuitBreakerOpen
    case rateLimited
    case unknown(String)

    public var errorDescription: String? {
        switch self {
        case .notInitialized:
            return "Layers SDK has not been initialized. Call Layers.initialize(config:) first."
        case .invalidConfig(let reason):
            return "Invalid configuration: \(reason)"
        case .networkError(let reason):
            return "Network error: \(reason)"
        case .persistenceError(let reason):
            return "Persistence error: \(reason)"
        case .queueFull:
            return "Event queue is full. Events are being dropped."
        case .circuitBreakerOpen:
            return "Circuit breaker is open. The SDK is temporarily not sending events."
        case .rateLimited:
            return "Rate limited by the server. Events will be retried later."
        case .unknown(let reason):
            return "Unknown Layers SDK error: \(reason)"
        }
    }
}

